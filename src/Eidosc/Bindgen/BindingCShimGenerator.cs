using System.Text;

namespace Eidosc.Bindgen;

/// <summary>
/// 自动 C shim 生成（P0 M4/M5）。
/// 规则：
/// 1. struct 按值参数 → 字段拆分 shim（递归展开为 <c>int64_t</c>/<c>double</c>/指针叶字段，
///    调用侧用 C99 compound literal 组装；Eidos 侧全部 64 位，可构造）；
/// 2. struct 按值返回 → 静态槽 + 指针返回 shim（Eidos 侧 <c>RawPtr</c>，不可重入；
///    读取字段需等 Eidosc 窄标量支持落地）；
/// 3. 窄标量（非 64 位整数、<c>float</c>、enum）→ <c>int64_t</c>/<c>double</c> 参数/返回 +
///    C 类型转换（Eidos 无法构造窄值，边界统一 64 位）；
/// 4. 其余 ABI 形态（变参、捕获回调、含 union/数组字段的 struct 参数）保持 SKIP。
/// </summary>
public sealed class BindingCShimGenerator
{
    private readonly CHeaderIr _ir;
    private readonly BindingTypeMapper _typeMapper;
    private readonly IReadOnlyDictionary<string, CBindingStruct> _structsByName;
    private readonly IReadOnlyDictionary<string, CBindingTypedef> _typedefs;

    public BindingCShimGenerator(CHeaderIr ir)
    {
        _ir = ir;
        _typeMapper = new BindingTypeMapper(ir);
        _structsByName = ir.Structs.ToDictionary(static st => st.Name, StringComparer.Ordinal);
        _typedefs = (ir.TypedefsSafe ?? [])
            .ToDictionary(static t => t.Name, StringComparer.Ordinal);
    }

    public bool HasShims => _ir.Functions.Any(NeedsShim);

    public string Generate()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Generated by eidosc pkg bind. Do not edit this file directly.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#include <stdint.h>");
        sb.AppendLine($"#include \"{Path.GetFileName(_ir.Header)}\"");
        sb.AppendLine();

        foreach (var fn in _ir.Functions.Where(NeedsShim).OrderBy(static fn => fn.Name, StringComparer.Ordinal))
        {
            GenerateShim(sb, fn);
            sb.AppendLine();
        }

        return sb.ToString();
    }

    private bool NeedsShim(CBindingFunction fn) =>
        fn.Parameters.Any(parameter => NeedsShim(parameter.Type)) ||
        NeedsShim(fn.ReturnType);

    private bool NeedsShim(CBindingType type)
    {
        var mapping = _typeMapper.Map(type);
        return mapping.Category == BindingTypeCategory.StructByValue
            ? type.Kind == CBindingTypeKind.Struct || type.Kind == CBindingTypeKind.Typedef && CanSplitStruct(type)
            : type.Kind is CBindingTypeKind.Primitive or CBindingTypeKind.Enum && NeedsNarrowing(type);
    }

    /// <summary>
    /// 当前编译器 FFI 边界只支持 64 位标量（E5337 白名单修复后窄类型仍无法从 Eidos 构造）；
    /// 窄标量（char/short/int/float/enum，不含 64 位整数与 bool）必须经 shim 窄化。
    /// Size==0（简单模式）视为未知 → 不 shim。
    /// </summary>
    private bool NeedsNarrowing(CBindingType type) =>
        type.Size is not (0 or 8) &&
        !(type.Kind == CBindingTypeKind.Primitive && type.Name is "bool" or "_Bool");

    private bool CanSplitStruct(CBindingType type) =>
        TrySplitStruct(type, "p", 0, out _, out _);

    private void GenerateShim(StringBuilder sb, CBindingFunction fn)
    {
        if (_typeMapper.Map(fn.ReturnType).Category == BindingTypeCategory.StructByValue)
        {
            GenerateStaticSlotReturnShim(sb, fn);
            return;
        }

        GenerateScalarShim(sb, fn);
    }

    private void GenerateScalarShim(StringBuilder sb, CBindingFunction fn)
    {
        var shimName = $"eidos_shim_{fn.Name}";
        var returnNarrowing = IsNarrowing(fn.ReturnType);
        var shimReturnType = returnNarrowing ? WideScalarType(fn.ReturnType) : fn.ReturnType.Spelling;

        BuildParametersAndArguments(fn, out var parameters, out var arguments);

        sb.Append($"{shimReturnType} {shimName}(");
        sb.Append(string.Join(", ", parameters));
        sb.AppendLine(")");
        sb.AppendLine("{");
        if (returnNarrowing)
        {
            sb.Append($"    return ({WideScalarType(fn.ReturnType)}){fn.Name}(");
            sb.Append(string.Join(", ", arguments));
            sb.AppendLine(");");
        }
        else
        {
            if (shimReturnType != "void")
                sb.Append("    return ");
            else
                sb.Append("    ");
            sb.Append($"{fn.Name}(");
            sb.Append(string.Join(", ", arguments));
            sb.AppendLine(");");
        }

        sb.AppendLine("}");
    }

    /// <summary>
    /// struct 按值返回：静态槽 + 指针返回。Eidos 侧绑定 <c>-> RawPtr</c>，
    /// 调用方在下次调用前复制字段（单静态槽，不可重入）。
    /// </summary>
    private void GenerateStaticSlotReturnShim(StringBuilder sb, CBindingFunction fn)
    {
        var shimName = $"eidos_shim_{fn.Name}";
        var returnType = fn.ReturnType.Spelling;

        BuildParametersAndArguments(fn, out var parameters, out var arguments);

        sb.AppendLine($"// {fn.ReturnType.Name} returned by value through a single static slot;");
        sb.AppendLine($"// callers must copy the result before the next call to {shimName}.");
        sb.AppendLine($"static {returnType} {shimName}_result;");
        sb.Append($"{returnType}* {shimName}(");
        sb.Append(string.Join(", ", parameters));
        sb.AppendLine(")");
        sb.AppendLine("{");
        sb.Append($"    {shimName}_result = {fn.Name}(");
        sb.Append(string.Join(", ", arguments));
        sb.AppendLine(");");
        sb.AppendLine($"    return &{shimName}_result;");
        sb.AppendLine("}");
    }

    private void BuildParametersAndArguments(
        CBindingFunction fn,
        out List<string> parameters,
        out List<string> arguments)
    {
        parameters = [];
        arguments = [];
        foreach (var parameter in fn.Parameters)
        {
            if (_typeMapper.Map(parameter.Type).Category == BindingTypeCategory.StructByValue)
            {
                if (!TrySplitStruct(parameter.Type, parameter.Name, 0, out var fields, out var literal))
                    continue; // NeedsShim 已保证可拆分；不可拆分的函数由 RawBindingGenerator SKIP

                foreach (var field in fields)
                {
                    parameters.Add($"{field.ShimType} {field.ParamName}");
                }

                arguments.Add(literal);
            }
            else if (NeedsNarrowing(parameter.Type))
            {
                parameters.Add($"{WideScalarType(parameter.Type)} {parameter.Name}");
                arguments.Add($"({parameter.Type.Spelling}){parameter.Name}");
            }
            else
            {
                parameters.Add($"{parameter.Type.Spelling} {parameter.Name}");
                arguments.Add(parameter.Name);
            }
        }
    }

    /// <summary>
    /// struct 按值参数递归拆分：叶字段产出 shim 参数（int64_t/double/指针原样）与
    /// compound literal 成员表达式；嵌套 struct 递归组装。
    /// </summary>
    private bool TrySplitStruct(CBindingType type, string paramName, int depth, out List<SplitField> fields, out string literal)
    {
        fields = [];
        literal = "";
        if (depth > 16)
            return false;

        if (type.Kind == CBindingTypeKind.Struct)
        {
            if (!_structsByName.TryGetValue(type.Name, out var st) || st.Fields.Count == 0)
                return false;

            var members = new List<string>();
            foreach (var field in st.Fields)
            {
                var fieldParamName = $"{paramName}_{BindingTypeMapper.ToEidosFunctionName(field.Name)}";
                if (!TrySplitStruct(field.Type, fieldParamName, depth + 1, out var nestedFields, out var member))
                    return false;

                fields.AddRange(nestedFields);
                members.Add(member);
            }

            literal = $"({type.Spelling}){{ {string.Join(", ", members)} }}";
            return true;
        }

        if (type.Kind == CBindingTypeKind.Typedef && _typedefs.TryGetValue(type.Name, out var typedef))
        {
            var underlying = typedef.UnderlyingType ?? new CBindingType(typedef.UnderlyingKind, typedef.Underlying, typedef.Underlying);
            return TrySplitStruct(underlying, paramName, depth + 1, out fields, out literal);
        }

        if (type.Kind is CBindingTypeKind.Union or CBindingTypeKind.Array)
            return false;

        if (type.Kind == CBindingTypeKind.Pointer)
        {
            fields.Add(new SplitField(paramName, type.Spelling, paramName));
            literal = paramName;
            return true;
        }

        if (type.Kind == CBindingTypeKind.Primitive)
        {
            var isFloat = type.Name == "float";
            var shimType = isFloat ? "double" : "int64_t";
            var cast = type.Name switch
            {
                "float" => "float",
                "double" or "long long" or "unsigned long long" => null,
                _ => type.Spelling
            };
            var member = cast == null ? paramName : $"({cast}){paramName}";
            fields.Add(new SplitField(paramName, shimType, member));
            literal = member;
            return true;
        }

        if (type.Kind == CBindingTypeKind.Enum)
        {
            fields.Add(new SplitField(paramName, "int64_t", $"({type.Spelling}){paramName}"));
            literal = $"({type.Spelling}){paramName}";
            return true;
        }

        return false;
    }

    private bool IsNarrowing(CBindingType type) =>
        (type.Kind is CBindingTypeKind.Primitive or CBindingTypeKind.Enum) && NeedsNarrowing(type);

    /// <summary>
    /// 窄标量的 shim 侧宽类型：<c>float</c> → <c>double</c>；其余（整数/enum）→ <c>int64_t</c>。
    /// </summary>
    private static string WideScalarType(CBindingType type) =>
        type.Name == "float" ? "double" : "int64_t";

    private sealed record SplitField(string ParamName, string ShimType, string LiteralMember);
}

